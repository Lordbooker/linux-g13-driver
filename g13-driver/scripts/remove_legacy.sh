#!/bin/bash
#
# Script: remove_legacy.sh
# Description: Finds and removes files of the old G13 driver version
#              (GTK tray icon in the daemon, Java config tool), installed via
#              'make install' or 'make install-user' of the old Makefile.
#
# Works on any distribution:
#   - Old files are identified by their content, not by distribution.
#   - Files owned by a package manager (pacman, dpkg, rpm) are NEVER touched;
#     they have to be removed with the package manager.
#   - The user configuration in ~/.config/g13 is always kept.
#
# Usage:
#   ./remove_legacy.sh            show findings, ask, then remove
#   ./remove_legacy.sh --yes      remove without asking
#   ./remove_legacy.sh --check    only report (exit code 1 if something was found)
#
# Run as normal user (not with sudo). sudo is requested only for system files.

set -u

MODE="interactive"
case "${1:-}" in
    "")       ;;
    --yes)    MODE="yes" ;;
    --check)  MODE="check" ;;
    -h|--help)
        sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
        exit 0 ;;
    *)
        echo "Unknown option: $1 (use --help)" >&2
        exit 2 ;;
esac

# Prefix for system paths. Only used for testing; empty in normal use.
ROOT="${LEGACY_ROOT:-}"

# --- Determine the target user's home directory ------------------------------
if [ "$(id -u)" -eq 0 ] && [ -n "${SUDO_USER:-}" ]; then
    if [ "$MODE" != "check" ]; then
        echo "Please run this script WITHOUT sudo:  make remove-legacy" >&2
        echo "It asks for sudo itself when system files have to be removed." >&2
        exit 2
    fi
    # --check from 'sudo make install': inspect the invoking user's home.
    USER_HOME="$(getent passwd "$SUDO_USER" | cut -d: -f6)"
else
    USER_HOME="$HOME"
fi

# --- Helpers -----------------------------------------------------------------

# Prints the owning package of a file, or nothing if no package owns it.
package_owner() {
    local file="$1"
    if command -v pacman >/dev/null 2>&1; then
        pacman -Qoq "$file" 2>/dev/null && return
    fi
    if command -v dpkg >/dev/null 2>&1; then
        dpkg -S "$file" 2>/dev/null | head -n1 | cut -d: -f1 && return
    fi
    if command -v rpm >/dev/null 2>&1; then
        rpm -qf "$file" 2>/dev/null | grep -v "not owned" && return
    fi
}

is_java_wrapper() {          # old 'g13-gui' wrapper script
    [ -f "$1" ] && grep -q "Linux-G13-GUI.jar" "$1" 2>/dev/null
}

is_old_driver_binary() {     # old daemon linked against GTK/AppIndicator
    [ -f "$1" ] && grep -aq "libappindicator" "$1" 2>/dev/null
}

is_old_user_service() {      # service generated by old 'make install-user'
    [ -f "$1" ] && grep -q "^ExecStart=.*/\.local/bin/linux-g13-driver" "$1" 2>/dev/null
}

is_g13_udev_rule() {
    [ -f "$1" ] && grep -q 'idProduct}=="c21c"' "$1" 2>/dev/null
}

STOP_SERVICE=0       # set when the old driver itself is found
USER_FILES=()        # removable without root
SYSTEM_FILES=()      # removable with sudo
PACKAGE_FILES=()     # owned by a package manager -> only reported

add_system_file() {
    local file="$1" owner
    owner="$(package_owner "$file")"
    if [ -n "$owner" ]; then
        PACKAGE_FILES+=("$file  (package: $owner)")
    else
        SYSTEM_FILES+=("$file")
    fi
}

# --- Detection ---------------------------------------------------------------

# 1) Old user-local installation (make install-user)
LOCAL_BIN="$USER_HOME/.local/bin"
LOCAL_UNIT="$USER_HOME/.config/systemd/user/g13.service"

if is_old_user_service "$LOCAL_UNIT"; then
    USER_FILES+=("$LOCAL_UNIT"); STOP_SERVICE=1
fi
if [ -f "$LOCAL_BIN/linux-g13-driver" ]; then
    USER_FILES+=("$LOCAL_BIN/linux-g13-driver"); STOP_SERVICE=1
fi
[ -f "$LOCAL_BIN/Linux-G13-GUI.jar" ]              && USER_FILES+=("$LOCAL_BIN/Linux-G13-GUI.jar")
is_java_wrapper "$LOCAL_BIN/g13-gui"               && USER_FILES+=("$LOCAL_BIN/g13-gui")

# The old install-user copied the udev rule to /etc (overrides /usr/lib).
is_g13_udev_rule "$ROOT/etc/udev/rules.d/99-g13.rules" \
    && add_system_file "$ROOT/etc/udev/rules.d/99-g13.rules"
# Earlier versions of 'make install' put the rule (with MODE="0666") into /usr/lib as
# 99-g13.rules; it is now 70-g13.rules. Package-owned copies are left alone.
is_g13_udev_rule "$ROOT/usr/lib/udev/rules.d/99-g13.rules" \
    && add_system_file "$ROOT/usr/lib/udev/rules.d/99-g13.rules"

# 2) Old system-wide installation (make install, PREFIX /usr or /usr/local)
for prefix in /usr /usr/local; do
    jar="$ROOT$prefix/share/java/linux-g13-driver/Linux-G13-GUI.jar"
    [ -f "$jar" ]                                  && add_system_file "$jar"
    is_java_wrapper "$ROOT$prefix/bin/g13-gui"     && add_system_file "$ROOT$prefix/bin/g13-gui"
    if is_old_driver_binary "$ROOT$prefix/bin/linux-g13-driver"; then
        add_system_file "$ROOT$prefix/bin/linux-g13-driver"; STOP_SERVICE=1
    fi
done

# --- Report ------------------------------------------------------------------
FOUND=$(( ${#USER_FILES[@]} + ${#SYSTEM_FILES[@]} + ${#PACKAGE_FILES[@]} ))

if [ "$FOUND" -eq 0 ]; then
    [ "$MODE" != "check" ] && echo "No files of the old G13 version found."
    exit 0
fi

echo "================================================================="
echo " Files of the old G13 driver / Java config tool found:"
echo "================================================================="
for f in "${USER_FILES[@]}";   do echo "  [user]    $f"; done
for f in "${SYSTEM_FILES[@]}"; do echo "  [system]  $f"; done
if [ ${#PACKAGE_FILES[@]} -gt 0 ]; then
    echo ""
    echo " Installed by a package manager (NOT removed by this script,"
    echo " please uninstall the package):"
    for f in "${PACKAGE_FILES[@]}"; do echo "  [package] $f"; done
fi
echo "================================================================="

if [ "$MODE" = "check" ]; then
    echo " Run 'make remove-legacy' (without sudo) to remove them."
    echo " Otherwise the old driver or config tool may keep being started."
    echo "================================================================="
    exit 1
fi

if [ $(( ${#USER_FILES[@]} + ${#SYSTEM_FILES[@]} )) -eq 0 ]; then
    exit 1   # only package files -> nothing this script may remove
fi

if [ "$MODE" = "interactive" ]; then
    read -r -p "Remove the files marked [user] and [system]? [y/N] " answer
    case "$answer" in
        y|Y|yes|j|J|ja) ;;
        *) echo "Aborted, nothing was removed."; exit 1 ;;
    esac
fi

# --- Removal -----------------------------------------------------------------
HAVE_SYSTEMCTL=0
command -v systemctl >/dev/null 2>&1 && HAVE_SYSTEMCTL=1

# Stop the old driver first, otherwise it keeps running from memory.
if [ "$STOP_SERVICE" -eq 1 ] && [ "$HAVE_SYSTEMCTL" -eq 1 ] && systemctl --user is-active --quiet g13 2>/dev/null; then
    echo "Stopping the running G13 service ..."
    systemctl --user disable --now g13 2>/dev/null || systemctl --user stop g13 2>/dev/null
fi

for f in "${USER_FILES[@]}"; do
    rm -f -- "$f" && echo "removed  $f"
done

UDEV_CHANGED=0
if [ ${#SYSTEM_FILES[@]} -gt 0 ]; then
    if [ "$(id -u)" -eq 0 ]; then SUDO=""; else SUDO="sudo"; fi
    echo "Removing system files (sudo may ask for your password) ..."
    for f in "${SYSTEM_FILES[@]}"; do
        if $SUDO rm -f -- "$f"; then
            echo "removed  $f"
            case "$f" in *udev/rules.d/*) UDEV_CHANGED=1 ;; esac
        else
            echo "FAILED   $f" >&2
        fi
    done
    # Remove the old Java directory if it is empty now.
    for prefix in /usr /usr/local; do
        dir="$ROOT$prefix/share/java/linux-g13-driver"
        [ -d "$dir" ] && $SUDO rmdir -- "$dir" 2>/dev/null && echo "removed  $dir/"
    done
    if [ "$UDEV_CHANGED" -eq 1 ] && [ -z "$ROOT" ] && command -v udevadm >/dev/null 2>&1; then
        $SUDO udevadm control --reload-rules
    fi
fi

[ "$HAVE_SYSTEMCTL" -eq 1 ] && systemctl --user daemon-reload 2>/dev/null

# Warn if an old driver process is still running (e.g. started manually).
# Match the process name (max. 15 chars: "linux-g13-drive"), not the command
# line, so editors or shells in the repository directory do not match.
if [ "$STOP_SERVICE" -eq 1 ] && command -v pgrep >/dev/null 2>&1 \
   && pgrep -u "$(id -u)" -x '[Ll]inux-[Gg]13-[Dd]rive' >/dev/null 2>&1; then
    echo ""
    echo "Note: a linux-g13-driver process is still running. Stop it before"
    echo "starting the new version (e.g. 'pkill -f linux-g13-driver')."
fi

echo ""
echo "Done. Your configuration in ~/.config/g13 was kept."
echo "Next steps: sudo make install  &&  systemctl --user enable --now g13"
